export const getCategoryById = (id) => categories.find(c => c.id === id)
export const getSubProduct = (categoryId, subProductName) => {
  const cat = getCategoryById(categoryId)
  return cat?.subProducts.find(s => s.name === subProductName)
}

export const allProducts = categories.flatMap(cat =>
  (cat.subProducts || []).map(sp => ({
    name: sp.name,
    image: sp.image,
    route: makeRoute(sp.name),
    category: cat.name,
    categoryId: cat.id,
    description: cat.description,
    longDescription: cat.longDescription,
    sizeOptions: cat.sizeOptions || [],
    gradeOptions: cat.gradeOptions || [],
    finishOptions: cat.finishOptions || [],
    specs: [
      { label: 'Category', value: cat.name },
      { label: 'Size Range', value: cat.sizeRange || 'Various' },
      { label: 'Grade', value: cat.grade || 'Industrial Grade' },
      { label: 'Finish', value: cat.finishing || 'Standard' },
    ],
  }))
)
